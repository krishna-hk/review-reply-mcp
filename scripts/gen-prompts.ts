// Turns prompts/*.md into a TypeScript file so the hosted server (which has no disk) can use them.
//   npm run gen
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const read = (f: string) => readFileSync(new URL(`../prompts/${f}`, import.meta.url), "utf8");
const guidance = Object.fromEntries(
  readdirSync(new URL("../prompts/", import.meta.url))
    .filter((f) => /^guidance-.+\.md$/.test(f))
    .map((f) => [f.slice("guidance-".length, -".md".length), read(f).trim()]),
);
writeFileSync(
  new URL("../src/generated/prompts.ts", import.meta.url),
  `// GENERATED by scripts/gen-prompts.ts from prompts/*.md. Do not edit by hand; run \`npm run gen\`.\nexport const TAGGING_TEMPLATE = ${JSON.stringify(read("tagging.md"))};\nexport const DRAFTING_TEXT = ${JSON.stringify(read("drafting.md"))};\nexport const GUIDANCE: Record<string, string> = ${JSON.stringify(guidance, null, 2)};\n`,
);
console.log("wrote src/generated/prompts.ts");
