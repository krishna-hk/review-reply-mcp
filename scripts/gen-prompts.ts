// Turns prompts/*.md into a TypeScript file so the hosted server (which has no disk) can use them.
//   npm run gen
import { readFileSync, writeFileSync } from "node:fs";
const read = (f: string) => readFileSync(new URL(`../prompts/${f}`, import.meta.url), "utf8");
writeFileSync(
  new URL("../src/generated/prompts.ts", import.meta.url),
  `// GENERATED by scripts/gen-prompts.ts from prompts/*.md. Do not edit by hand; run \`npm run gen\`.\nexport const TAGGING_TEMPLATE = ${JSON.stringify(read("tagging.md"))};\nexport const DRAFTING_TEXT = ${JSON.stringify(read("drafting.md"))};\n`,
);
console.log("wrote src/generated/prompts.ts");
